/**
 * Editors type an icon name in Strapi (the `icon` field of a link, e.g. "monitor").
 * Unknown or empty names fall back to a neutral link icon, so a typo never breaks the menu.
 */
const registry: Record<string, LucideIcon> = {
  atom: Atom,
  award: Award,
  "badge-check": BadgeCheck,
  bed: BedDouble,
  book: BookOpen,
  "book-open": BookOpen,
  briefcase: Briefcase,
  building: Building2,
  bus: Bus,
  calendar: CalendarDays,
  "circle-help": CircleHelp,
  "clipboard-list": ClipboardList,
  compass: Compass,
  download: Download,
  "file-check": FileCheck2,
  flask: FlaskConical,
  "folder-kanban": FolderKanban,
  gavel: Gavel,
  "graduation-cap": GraduationCap,
  "heart-pulse": HeartPulse,
  inbox: Inbox,
  info: Info,
  landmark: Landmark,
  layers: Layers,
  library: Library,
  lightbulb: Lightbulb,
  "list-checks": ListChecks,
  mail: Mail,
  "map-pin": MapPin,
  megaphone: Megaphone,
  message: MessageSquareQuote,
  monitor: Monitor,
  newspaper: Newspaper,
  palette: Palette,
  "pen-line": PenLine,
  phone: Phone,
  trophy: Trophy,
  tv: Tv,
  "user-search": UserSearch,
  users: Users,
  wallet: Wallet,
};

export function iconFor(name: string | null | undefined): LucideIcon {
  return (name && registry[name]) || Link2;
}
